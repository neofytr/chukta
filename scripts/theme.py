"""Generates static/theme.css: Material 3 color roles from tonal palettes, for four seeds in light and dark.

Tone is CIE L*, as in Material's tonal model. Run: python3 scripts/theme.py
"""
import math
import pathlib

SEEDS = {"forest": (158, 36), "bay": (272, 44), "peony": (355, 42), "marigold": (78, 42)}
LIGHT = dict(primary=40, on_primary=100, primary_container=90, on_primary_container=30)
DARK = dict(primary=80, on_primary=20, primary_container=30, on_primary_container=90)
NEUTRAL_LIGHT = dict(surface=98, surface_dim=87, surface_bright=98, surface_container_lowest=100, surface_container_low=96, surface_container=94,
                     surface_container_high=92, surface_container_highest=90, on_surface=10, inverse_surface=20, inverse_on_surface=95)
NEUTRAL_DARK = dict(surface=6, surface_dim=6, surface_bright=24, surface_container_lowest=4, surface_container_low=10, surface_container=12,
                    surface_container_high=17, surface_container_highest=22, on_surface=90, inverse_surface=90, inverse_on_surface=20)


def _gamma(c):
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def _rgb(lightness, chroma, hue):
    a, b = chroma * math.cos(math.radians(hue)), chroma * math.sin(math.radians(hue))
    fy = (lightness + 16) / 116
    fx, fz = fy + a / 500, fy - b / 200
    inv = lambda t: t ** 3 if t ** 3 > 0.008856 else (116 * t - 16) / 903.3
    x, y, z = 0.95047 * inv(fx), inv(fy), 1.08883 * inv(fz)
    return (3.2406 * x - 1.5372 * y - 0.4986 * z, -0.9689 * x + 1.8758 * y + 0.0415 * z, 0.0557 * x - 0.2040 * y + 1.0570 * z)


def tone(hue, chroma, level):
    """The most colorful in-gamut sRGB color at this tone, keeping hue."""
    low, high = 0.0, chroma
    best = _rgb(level, 0, hue)
    for _ in range(18):
        mid = (low + high) / 2
        rgb = _rgb(level, mid, hue)
        if all(-0.0005 <= c <= 1.0005 for c in rgb):
            best, low = rgb, mid
        else:
            high = mid
    return "#" + "".join(f"{round(max(0, min(1, _gamma(max(0, c)))) * 255):02x}" for c in best)


def luminance(color):
    channels = [int(color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    r, g, b = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    x, y = sorted((luminance(a), luminance(b)), reverse=True)
    return (x + 0.05) / (y + 0.05)


def harmonize(hue, seed_hue):
    """Moves a status hue slightly toward the seed, so it belongs to the palette but keeps its meaning."""
    delta = (seed_hue - hue + 180) % 360 - 180
    return (hue + max(-12, min(12, delta / 2))) % 360


def family(prefix, hue, chroma, table):
    return {k.replace("primary", prefix): tone(hue, chroma, v) for k, v in table.items()}


def scheme(hue, chroma, dark):
    table = DARK if dark else LIGHT
    roles = {}
    roles |= family("primary", hue, chroma, table)
    roles |= family("secondary", hue, 16, table)
    roles |= family("tertiary", (hue + 60) % 360, 28, table)
    roles |= family("error", 30, 80, table)
    roles |= family("success", harmonize(145, hue), 52, table)
    roles |= family("warning", harmonize(75, hue), 58, table)
    roles |= {k: tone(hue, 5, v) for k, v in (NEUTRAL_DARK if dark else NEUTRAL_LIGHT).items()}
    roles["on_surface_variant"] = tone(hue, 9, 80 if dark else 30)
    roles["outline"] = tone(hue, 9, 60 if dark else 50)
    roles["outline_variant"] = tone(hue, 9, 30 if dark else 80)
    roles["inverse_primary"] = tone(hue, chroma, 40 if dark else 80)
    roles["scrim"] = roles["shadow"] = "#000000"
    return roles


def main():
    css = ["/* Generated by scripts/theme.py. Material 3 color roles over CIE L* tonal palettes. */"]
    worst = 99.0
    for name, (hue, chroma) in SEEDS.items():
        for dark in (False, True):
            r = scheme(hue, chroma, dark)
            for fg, bg in (("on_primary", "primary"), ("on_primary_container", "primary_container"), ("on_secondary_container", "secondary_container"),
                           ("on_tertiary_container", "tertiary_container"), ("on_error_container", "error_container"), ("on_success_container", "success_container"),
                           ("on_warning_container", "warning_container"), ("on_surface", "surface"), ("on_surface_variant", "surface_container_high"),
                           ("on_error", "error"), ("on_success", "success")):
                worst = min(worst, contrast(r[fg], r[bg]))
            body = ";".join(f"--md-{k.replace('_', '-')}:{v}" for k, v in r.items())
            mode = "dark" if dark else "light"
            prefix = ":root," if name == "forest" and not dark else ""
            css.append(f'{prefix}:root[data-seed="{name}"][data-mode="{mode}"]{{{body};color-scheme:{mode}}}')
    out = pathlib.Path(__file__).parent.parent / "static" / "theme.css"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(css) + "\n")
    assert worst >= 4.5, f"contrast too low: {worst:.2f}"
    print(f"wrote {out.name}, lowest text contrast across all themes: {worst:.2f}:1")


if __name__ == "__main__":
    main()
